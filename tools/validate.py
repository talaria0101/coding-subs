#!/usr/bin/env python3
"""Data-integrity gate for a coding-subs research pass.

    python3 tools/validate.py [PASS_DIR ...]   # default: newest YYYY-MM-DD dir
    python3 tools/validate.py --all            # every pass in the repo

Exit code 0 only when every check passes. Each check exists because a real,
named defect got past the previous validator; CHECKS below is the registry, one
entry per registered check, and `gate-count-claims` refuses any count in the
documentation that disagrees with it. The failing-before evidence for every
check is in docs/reviews-*.md, with the plant fixtures it was demonstrated
against generated by tools/make-plants.py and run by tests/run-plants.sh.

Every check falls into one of four families.

**Shape.** A row must have the field count its header declares; a cell must hold
the kind of value its column name promises; a row count or a cited path in prose
must be what the files on disk say; a plan price, a monthly token count and a
cost per million on one row must describe one quantity in three units; a row's
token count must be the division it claims to have performed; a token figure's
magnitude must agree with its own column's unit and with what a monthly
allowance can physically be.

**Sourcing.** Every number must carry an evidence class from the closed
vocabulary the root README declares; every money figure quoted in a references
file must be present in the archived bytes of the page that entry cites; every
recorded SHA-256 must be the hash of the bytes actually archived; every archived
source must have a fetch log entry and every logged retrieval an archived file.

**Semantics.** A capability score must be traceable to a leaderboard row for
that exact SKU rather than inherited from a different one; a per-model dollar
ceiling must say whether it is independent or drawn against a shared pool; a
derived $/M or tokens/month figure must state the traffic mix it was computed
under; a provenance string must not assert a dated measurement that no fetch log
entry records.

**Self-description.** A document claiming a number of checks must state the
number the registry holds.

None of these can be verified by reading a report, which is why they are checks
rather than conventions.
"""
from __future__ import annotations

import csv
import hashlib
import importlib.util
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# name -> (what it enforces, what defect it was added for)
CHECKS: dict[str, str] = {
    "layout": "every pass has data/, references/, sources/ and a README",
    "gate-count-claims": "a document claiming a number of checks that disagrees with CHECKS",
    "field-count": "7 malformed CSV rows shipped past a green run across two passes",
    "field-columns": "an arity-preserving column shift puts every value in the wrong column",
    "cost-arithmetic": "a price, a token count and a $/M must describe one quantity",
    "cost-identity": "a row's token count must be the division the row states it performed",
    "evidence-label": "a number without a source is not evidence",
    "evidence-vocabulary": "an evidence class outside the set the root README declares",
    "no-future-pass": "a pass directory cannot be dated after the machine's clock",
    "fetch-log-corroborates": "every archived source needs a log entry and every logged hash must be the hash of the bytes",
    "report-matches-data": "row counts, cited paths and fetch tallies the report quotes must match the CSVs and the log",
    "model-slug-joins": "a plan row naming a model must join to a model in the landscape",
    "ladder-price-on-page": "a ladder price must appear in the page it cites",
    "quoted-money-on-page": "a figure quoted in references/*.md must be on the page it cites",
    "unit-scale": "25.81 yi (10^8) was read as 25.81 billion and reached a headline verdict",
    "unscored-model": "a score inherited from a different SKU ranks as a real capability score",
    "lookup-against-board": "a lookup row must say what the archived leaderboard payload actually holds",
    "provenance-in-log": "a provenance string asserting a dated lookup no fetch log entry records",
    "shared-cap": "a per-model ceiling was published without saying the ceilings share a pool",
    "mix-declared": "a derived $/M or tokens/month figure whose row omits its traffic mix",
}

failures: list[str] = []

# How far two figures derived from the same inputs may differ before they are
# treated as different quantities rather than as rounding. Every figure this
# repo publishes is rounded to four decimal places on a rate or to the nearest
# whole token-million, so five per cent is generous and one per cent would
# reject correct data.
ARITHMETIC_TOLERANCE = 0.05

# CJK magnitude suffixes and the power of ten each stands for. A note carrying
# one of these has to be converted against the stored row, never copied: yi is
# 10^8, so 25.81 yi is 2,581,000,000 and not 25.81 billion.
CJK_SCALE = {"万": 1e4, "萬": 1e4, "亿": 1e8, "億": 1e8, "兆": 1e12}

NUM_WORDS = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12,
    "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16,
    "seventeen": 17, "eighteen": 18, "nineteen": 19, "twenty": 20,
}

# The closed evidence vocabulary, exactly as the root README declares it. A class
# outside this set is a class no reader of that table can interpret, which is why
# it is refused rather than merely noted.
EVIDENCE_CLASSES = frozenset({
    "FIRST-PARTY-COMPUTED",
    "FIRST-PARTY-PRICE-ONLY",
    "MEASURED",
    "DOCUMENTED",
    "THIRD-PARTY",
    "UNKNOWN",
})

# A word that records a figure this pass could not re-verify from the sources it
# archived. It is not evidence, which is the point of it, so it is not in
# EVIDENCE_CLASSES and the vocabulary check reports it separately.
CARRY_MARKER = "CARRIED-FORWARD"


def check(cond: bool, msg: str) -> None:
    if not cond:
        failures.append(msg)


def passes() -> list[Path]:
    return sorted(p for p in ROOT.iterdir() if p.is_dir() and re.fullmatch(r"\d{4}-\d{2}-\d{2}", p.name))


def latest() -> Path:
    found = passes()
    check(bool(found), "no YYYY-MM-DD pass directory found")
    return found[-1] if found else ROOT


def rel(path: Path) -> str:
    """Path relative to the repo root, whether or not ROOT is a prefix of it.

    A pass directory can be passed in as a relative path, and `relative_to`
    raises rather than degrading. Reporting a bare path is better than a
    traceback in a gate that is supposed to be readable.
    """
    try:
        return str(path.resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def read_rows(path: Path) -> tuple[list[str], list[list[str]]]:
    """Rows of a CSV, skipping a leading prose preamble whose header starts '#'."""
    raw = path.read_text(encoding="utf-8", errors="replace").splitlines()
    start = 0
    while start < len(raw) and raw[start].lstrip().startswith("#"):
        start += 1
    if start >= len(raw):
        return [], []
    rows = list(csv.reader(raw[start:]))
    return (rows[0] if rows else []), rows[1:]


def data_rows(rows: list[list[str]]) -> list[list[str]]:
    """Data rows only: a blank line, or a line holding one empty field, is not a row."""
    return [r for r in rows if r and not (len(r) == 1 and not r[0].strip())]


def _num(value):
    """A numeric cell, or None.

    Accepts thousands separators, a currency symbol, a trailing CJK magnitude
    suffix and the English number words that appear in prose. A cell that is not
    a number is UNKNOWN rather than zero, so a row that reads FREE is not
    silently treated as a row worth nothing.
    """
    if value is None:
        return None
    text = str(value).strip().replace(",", "").replace("$", "").replace("%", "")
    if not text or text.upper() in ("UNKNOWN", "N/A", "NA", "-"):
        return None
    scale = 1.0
    for suffix, factor in CJK_SCALE.items():
        if text.endswith(suffix):
            scale = factor
            text = text[: -len(suffix)].strip()
            break
    try:
        return float(text) * scale
    except ValueError:
        pass
    lowered = text.lower()
    if lowered in NUM_WORDS:
        return float(NUM_WORDS[lowered]) * scale
    return None


def _row_contract(path: Path) -> list[str]:
    """What a CSV's own `#` preamble says its rows are.

    Some of this repository's databases are *derived* artefacts, regenerable from
    a named archived source: the model landscapes come out of a leaderboard page,
    the price grids out of the vendor pages they quote. Those files legitimately
    carry no per-row source column, because their provenance is the file. The
    rest are tables of observation, and every row of those has to say where its
    numbers came from.

    The distinction is read from the preamble the file already carries rather
    than hard-coded by filename, so a new derived file declares itself and a new
    table of observation gets no free pass. A file whose preamble says nothing is
    treated as a table of observation, which is the stricter reading.
    """
    found = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.lstrip().startswith("#"):
            break
        low = line.lower()
        if ("regenerat" in low or "reproduce" in low or "comes out of" in low
                or "extracted" in low or "derived" in low or "byte for byte" in low
                or "payload" in low):
            found.append(line)
    return found


def check_layout(pass_dir: Path) -> None:
    for sub in ("data", "references", "sources"):
        check((pass_dir / sub).is_dir(), f"[layout] missing {sub}/ in {pass_dir.name}")
    check((pass_dir / "README.md").is_file(), f"[layout] missing README.md in {pass_dir.name}")
    check((ROOT / "README.md").is_file(), "[layout] missing root README.md")
    check((ROOT / "docs").is_dir(), "[layout] missing docs/ (reviews live there)")


def check_gate_count_claims(pass_dir: Path) -> None:
    """A document that states how many checks this gate runs must state it right.

    The root README, a pass report and this module's own docstring have all, at
    different times, carried a number that had drifted from the registry. A count
    that is wrong is not a typo: a reader uses it to decide whether the gate
    covers what they are about to rely on. The registry is the authority and the
    documents are checked against it.
    """
    words = {
        "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
        "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19, "twenty": 20,
    }
    pattern = re.compile(r"\*\*(" + "|".join(words) + r"|\d+)\s+checks\b", re.IGNORECASE)
    for path in (ROOT / "README.md", pass_dir / "README.md", Path(__file__).resolve()):
        if not path.is_file():
            continue
        for offset, line in enumerate(
            path.read_text(encoding="utf-8", errors="replace").splitlines(), start=1
        ):
            for match in pattern.finditer(line):
                token = match.group(1).lower()
                claimed = int(token) if token.isdigit() else words[token]
                if claimed != len(CHECKS):
                    failures.append(
                        f"[gate-count-claims] {rel(path)} line {offset} says the gate runs "
                        f"{claimed} checks; CHECKS in {rel(Path(__file__))} registers "
                        f"{len(CHECKS)}"
                    )


def check_field_counts(pass_dir: Path) -> None:
    """The check the 2026-09-20 pass needed and did not have."""
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header or len(header) < 2:
            # A single-column ledger is prose or a key/value file, not a table.
            continue
        width = len(header)
        for offset, row in enumerate(rows, start=1):
            if not row or (len(row) == 1 and not row[0].strip()):
                continue
            if len(row) != width:
                failures.append(
                    f"[field-count] {rel(path)} data row {offset} has "
                    f"{len(row)} fields, header has {width} (columns from field "
                    f"{min(len(row), width) + 1} onward are shifted)"
                )


# What kind of value each column name promises. A column name is a type
# declaration, and a cell that cannot be that type is either in the wrong column
# or the row has slid sideways.
#
# Each entry is deliberately narrow. A pattern wide enough to catch every shift
# is also wide enough to reject correct data, and a check that rejects correct
# data is worse than one that passes a defect. Three wider attempts failed on
# this repo's own history and are recorded in docs/reviews-2026-10-06.md: a
# pattern on `evidence` rejected 37 rows of 2026-09-20's agents-universe.csv that
# legitimately hold a URL or a file path, a pattern on `source_quality` rejected
# 43 rows of 2026-09-13's providers-database.csv whose values are free text by
# design, and a pattern on `model_slug` rejected 100+ rows of 2026-10-02's
# mix-sensitivity-all.csv, where the column holds display names rather than slugs.
COLUMN_VALUE_PATTERNS: tuple[tuple[str, str], ...] = (
    ("source_url", r"^https?://\S+$"),
    ("read_date", r"^\d{4}-\d{2}-\d{2}$"),
    ("lookup_verdict", r"^(scored|notFound|noIndex|scored-\d{4}-\d{2}-\d{2})$"),
    ("present_on_board", r"^(yes|no)$"),
)


def check_column_values(pass_dir: Path) -> None:
    """A cell must hold the kind of value its column name promises.

    `field-count` catches a row with the wrong number of fields. It cannot catch
    a row with the right number of fields whose values have slid sideways, and a
    sideways shift is the quieter failure: the file parses, the arity is right,
    and every value from the shift onward reads as plausible content of the wrong
    kind. This check reads the values against the header names.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        expectations = []
        for i, name in enumerate(header):
            lowered = name.strip().lower()
            for key, pattern in COLUMN_VALUE_PATTERNS:
                if lowered == key:
                    expectations.append((i, lowered, re.compile(pattern)))
            # An evidence class is a class drawn from the declared vocabulary,
            # plus the one carry marker. Those are the only values a reader of
            # that column can interpret, so they are the values it may hold.
            # Membership is also checked by `evidence-vocabulary`; listing them
            # here as well means a shift that lands a URL or a date in this column
            # is caught by shape first, with the membership message available
            # when nothing has been shifted.
            #
            # The check is gated on the column being present, because a vocabulary
            # is a property of a repository and cannot be retrofitted onto a pass
            # that predates the table. 2026-10-02 is the first pass carrying
            # `evidence_class`.
            if lowered == "evidence_class":
                expectations.append(
                    (i, lowered, tuple(sorted(EVIDENCE_CLASSES)) + (CARRY_MARKER,))
                )
        if not expectations:
            continue
        for offset, row in enumerate(rows, start=1):
            if not row or len(row) != len(header):
                continue
            for i, name, pattern in expectations:
                value = row[i].strip()
                if not value:
                    continue
                if isinstance(pattern, tuple):
                    if value in pattern:
                        continue
                elif pattern.match(value):
                    continue
                failures.append(
                    f"[field-columns] {rel(path)} data row {offset}: column "
                    f"{name!r} holds {value!r}, which is not a value of the kind "
                    f"that column is for. Either this value belongs in another "
                    f"column or the row has slid sideways: a surplus unquoted "
                    f"comma paired with a missing empty cell keeps the field "
                    f"count correct while shifting every value after it."
                )


def _role_candidates(index: dict[str, int], role: str) -> list[str]:
    """Columns that play a role, most specific first.

    Columns are resolved by role rather than by an exact-name allow-list because
    an allow-list cannot see the pass that introduces a new column name, and the
    consequence is silent blindness: `cost-arithmetic` matched a fixed list of
    token-column names, none of which the 2026-10-06 pass uses, so the check had
    never once examined a row of the newest pass. A pass that cannot be seen is
    not a pass that is clean.
    """
    if role == "price":
        return [n for n in ("plan_price_usd_month", "price_usd_month", "price") if n in index]
    if role == "per_m":
        return [n for n in ("usd_per_mtok", "usd_per_m_tokens") if n in index]
    if role == "tokens_m":
        names = [n for n in index if TOKEN_COLUMN_PATTERN.match(n)]
        # `_measured` is a user meter and `tokens_m_at_ceiling` is the ceiling a
        # yield was derived from, so both are excluded from this role: a plan
        # price divided by a metered reading is not the plan's $/M.
        names = [
            n for n in names
            if not n.endswith(DIFFERENT_QUANTITY_SUFFIX) and n != "tokens_m_at_ceiling"
        ]
        return sorted(names)
    return []


def _resolve(index: dict[str, int], probe: list[str], role: str, want_number) -> str | None:
    """First candidate for `role` whose value in the first data row is a number."""
    for name in _role_candidates(index, role):
        if index[name] < len(probe) and want_number(probe[index[name]]):
            return name
    return None


def _wants_number(value: str) -> bool:
    number = _num(value)
    return number is not None and number > 0


def check_cost_arithmetic(pass_dir: Path) -> None:
    """price, tokens and $/M must agree. A row that fails is not publishable.

    The three cells have to be the same quantity in three units. A per-M rate is
    only meaningful when it is the same quantity as the token count it came from,
    so the ceiling a yield was derived from is excluded from the token role rather
    than compared against the advertised figure on the same row.

    Columns are resolved by role and the resolved columns are recorded, because
    an exact-name allow-list cannot see a pass that renames a column, and a check
    that cannot see a pass reports it as clean. Resolving by role made this check
    read the 2026-10-06 pass for the first time and immediately find a row there
    it had never looked at.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        index = {name.strip().lower(): i for i, name in enumerate(header)}
        live = data_rows(rows)
        if not live:
            continue
        price_col = _resolve(index, live[0], "price", _wants_number)
        per_col = _resolve(index, live[0], "per_m", _wants_number)
        tok_col = _resolve(index, live[0], "tokens_m", _wants_number)
        if not (price_col and tok_col and per_col):
            continue
        for offset, row in enumerate(live, start=1):
            if len(row) <= max(index[c] for c in (price_col, tok_col, per_col)):
                continue
            price = _num(row[index[price_col]])
            tokens = _num(row[index[tok_col]])
            per_m = _num(row[index[per_col]])
            if not price or not tokens or not per_m or price <= 0 or tokens <= 0 or per_m <= 0:
                continue
            # A `*_m` column is already in millions, so price / tokens is $/M.
            expected = price / tokens
            ratio = expected / per_m
            if abs(ratio - 1.0) > ARITHMETIC_TOLERANCE:
                failures.append(
                    f"[cost-arithmetic] {rel(path)} data row {offset}: "
                    f"{price_col}={price:g} / {tok_col}={tokens:g}M tokens = "
                    f"${expected:.4f}/M but the row's {per_col} reads "
                    f"${row[index[per_col]].strip()}/M "
                    f"({per_m / expected:.2f}x off). price, tokens and $/M are the "
                    f"same quantity in three units; the per-model rate is on the same row."
                )


def _identity_fields(index: dict[str, int]) -> dict[str, int] | None:
    """The columns that together name one plan x model x mix x measurement.

    A file that does not carry all of them is skipped: a file without a mix has
    nothing to declare, and a file without a plan has no per-plan price to
    divide.
    """
    names = {
        "plan": next((index[n] for n in ("plan", "provider_plan", "plan_name")
                      if n in index), None),
        "model": next((index[n] for n in ("model", "model_sold", "sku")
                       if n in index), None),
        "mix": next((index[n] for n in ("traffic_mix", "mix", "traffic_mix_used",
                                        "mix_used", "assumed_mix")
                     if n in index), None),
        "ceiling": next((index[n] for n in ("tokens_m_advertised", "tokens_m_converted",
                                            "monthly_tokens_m", "tokens_m",
                                            "plan_monthly_tokens")
                         if n in index), None),
        "pool": next((index[n] for n in ("monthly_pool_usd", "monthly_ceiling_usd",
                                         "per_model_cap_usd", "plan_ceiling_usd")
                      if n in index), None),
        "rate": next((index[n] for n in ("blended_usd_per_mtok", "usd_per_mtok",
                                          "usd_per_m_tokens",
                                          "effective_usd_per_mtok_own_meter",
                                          "conversion_usd_per_mtok")
                      if n in index), None),
    }
    if any(v is None for v in names.values()):
        return None
    return names


def check_cost_identity(pass_dir: Path) -> None:
    """The row must be the division it says it is: ceiling / rate = tokens.

    `cost-arithmetic` holds the three columns that state one quantity in three
    units - plan price, monthly tokens, cost per million - against each other. It
    cannot see a second quantity on the same row, and the newest pass has one: a
    model price per million from which a token yield is derived, sitting beside a
    per-model dollar ceiling. The Go Plus row of 2026-10-06 derived its token
    count from a $120 figure while its per-M rate came from a different one; the
    three columns `cost-arithmetic` reads were internally consistent and the row
    was wrong anyway.

    Two relationships are checked, and they are different relationships. Rows
    describing the same plan x model x mix x token-measurement must scale
    together, because a scale factor is the only thing a second reading of one
    quantity can change. And a row that states both a dollar ceiling and a rate
    must satisfy ceiling / rate = tokens, which is the division the row claims to
    have performed.

    What is deliberately **not** checked is plan price / tokens against the
    model's own `blended_usd_per_mtok`. Those are different quantities - what the
    subscriber pays for the whole plan against what the vendor charges an API
    customer for the model - and their ratio is the plan's whole economics.
    Treating them as two estimates of one number was an over-reach in the first
    version of this check and it rejected 28 correct rows. `cost-arithmetic`
    already holds the former against `usd_per_mtok`.

    Its limit is stated here because it has been hit. **An arity-preserving column
    shift moves the values under the column names without changing either, and
    every arithmetic check reads by name.** A surplus comma in one cell plus a
    removed empty cell elsewhere leaves this file arity-correct with `rankable`
    holding what used to be the evidence class and `evidence_class` holding a URL;
    no amount of arithmetic on the row detects it, because every number in the row
    is still exactly what its new name says it is. `field-columns` is the check
    that sees it, and it is the reason both run.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        index = {name.strip().lower(): i for i, name in enumerate(header)}
        cols = _identity_fields(index)
        if cols is None:
            continue
        plan_i, model_i, mix_i = cols["plan"], cols["model"], cols["mix"]
        ceil_i, pool_i, rate_i = cols["ceiling"], cols["pool"], cols["rate"]
        ceil_name = header[ceil_i]
        rate_name = header[rate_i]
        pool_name = header[pool_i]
        both_caps = "per_model_cap_usd" in index and "monthly_pool_usd" in index

        groups: dict[tuple, list[tuple[int, float, float]]] = {}
        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) != len(header):
                continue
            tokens = _num(row[ceil_i])
            rate = _num(row[rate_i])
            if not tokens or not rate or tokens <= 0 or rate <= 0:
                continue
            key = tuple(row[i].strip().lower() for i in (plan_i, model_i, mix_i, ceil_i))
            groups.setdefault(key, []).append((offset, tokens, rate))
        for (plan, model, mix, column), members in groups.items():
            if len(members) < 2:
                continue
            first_offset, first_tokens, first_rate = members[0]
            for offset, tokens, rate in members[1:]:
                t_ratio = tokens / first_tokens
                r_ratio = rate / first_rate
                if abs(t_ratio - r_ratio) / max(t_ratio, r_ratio) > ARITHMETIC_TOLERANCE:
                    failures.append(
                        f"[cost-identity] {rel(path)} data row {offset} and data row "
                        f"{first_offset} both describe plan {plan!r}, model {model!r} "
                        f"under mix {mix!r}, and both carry a dollar ceiling in "
                        f"{pool_name}, but {column} differs by {t_ratio:.2f}x and "
                        f"{rate_name} differs by {r_ratio:.2f}x. Two rows of one "
                        f"quantity cannot scale differently: one of them is counting a "
                        f"different dollar figure."
                    )

        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) != len(header):
                continue
            tokens = _num(row[ceil_i])
            rate = _num(row[rate_i])
            if not tokens or not rate or tokens <= 0 or rate <= 0:
                continue
            if both_caps:
                pool = _num(row[index["monthly_pool_usd"]]) or 0.0
                cap = _num(row[index["per_model_cap_usd"]]) or 0.0
                effective = min(v for v in (pool, cap) if v > 0) if (pool or cap) else 0.0
            else:
                effective = _num(row[pool_i]) or 0.0
            if effective <= 0:
                continue
            expected = effective / rate
            if abs(expected - tokens) / expected > ARITHMETIC_TOLERANCE:
                failures.append(
                    f"[cost-identity] {rel(path)} data row {offset}: "
                    f"{pool_name}={row[pool_i].strip()} / {rate_name}="
                    f"{row[rate_i].strip()} = {expected:,.0f}M, but {ceil_name} reads "
                    f"{row[ceil_i].strip()}. The row states the division it performed "
                    f"and it does not produce the count on the same row."
                )


def check_evidence_labels(pass_dir: Path) -> None:
    """A figure must be attributable, and the attribution must be reachable.

    `evidence-label` covers three cases, in the order they matter. A row with no
    evidence cell at all is unsourced. An `evidence_class` outside the declared
    vocabulary is a class no reader of the evidence table can interpret. A figure
    citing no URL is not verifiable by anyone, which is the defect this check was
    originally written for and the one it silently tolerated: a non-empty string
    of any content passed as evidence.

    A `source` column that holds a bare slug (`modelsdev-api.json`,
    `peter123023/awesome-free-llm-api`) is a repository reference rather than a
    URL. Such rows are still reported, against the file's own declared
    provenance rather than as arithmetic failures.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    # Which columns may satisfy a row's evidence requirement. `evidence` is
    # deliberately absent: 2026-09-20's providers-database.csv and
    # agents-universe.csv use it as free text, so a pattern on it rejects correct
    # rows, and those rows carry their reference in `source` instead.
    label_cols = ("source_url", "source", "source_quality", "confidence")
    # The evidence-label check's own history is recorded in the code beside the
    # column-pattern table above; what is recorded here is the shape.
    # `vendor_source` is a page file, not a URL, and the check below says so
    # rather than treating every non-URL as absent.
    page_reference_columns = {"vendor_source"}
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        index = {name.strip().lower(): i for i, name in enumerate(header)}
        page_cols = [index[n] for n in page_reference_columns if n in index]
        has_labels = any(c in name for name in index for c in label_cols)
        if not has_labels and "evidence_class" not in index:
            continue
        contract = _row_contract(path)
        present = [c for c in label_cols if any(c in name for name in index)]
        class_i = index.get("evidence_class")
        url_cols = [index[n] for n in index
                    if n in ("source_url", "source", "url") or n.endswith("_url")]
        date_cols = [index[n] for n in index
                     if n in ("read_date", "access_date", "fetched_date", "date")]
        siblings = {q.name for q in data.glob("*")}
        if pass_dir.joinpath("sources").is_dir():
            siblings |= {q.name for q in pass_dir.joinpath("sources").glob("*")}
        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) != len(header):
                continue
            if not any(c.strip() for c in row):
                continue
            urls = [row[i].strip() for i in url_cols if row[i].strip()]
            openable = [u for u in urls if re.match(r"^https?://\S+$", u)]
            derived = bool(contract) and bool(urls)
            values = [
                row[index[name]].strip() for name in index
                if any(c in name for c in present)
            ]
            # The two passes before 2026-10-02 name no URL anywhere, so this
            # check has nothing to compare a reference against. That is a finding
            # about those passes, recorded once in the review file rather than as
            # 118 rows on every run; `evidence-vocabulary` and
            # `fetch-log-corroborates` still cover them.
            if not openable and pass_dir.name < "2026-10-02":
                continue
            pages = [row[i].strip() for i in page_cols if row[i].strip()]
            if pages and not urls and pass_dir.joinpath("sources").is_dir():
                if all((pass_dir / "sources" / pg).is_file() for pg in pages):
                    # The row cites the archived page by file name, and the page
                    # is here. `fetch-log-corroborates` checks the bytes.
                    if class_i is not None:
                        declared = row[class_i].strip()
                        if (declared and declared != CARRY_MARKER
                                and declared not in EVIDENCE_CLASSES):
                            failures.append(
                                f"[evidence-label] {rel(path)} data row {offset}: "
                                f"evidence_class={declared!r} is outside the vocabulary "
                                f"the root README declares "
                                f"({' | '.join(sorted(EVIDENCE_CLASSES))}). A class no "
                                f"reader of that table can interpret is not an evidence "
                                f"class; pick one of the declared six, or record the row "
                                f"as {CARRY_MARKER} to say the figure was not re-verified."
                            )
                    continue
            if not any(values) and not urls:
                failures.append(
                    f"[evidence-label] {rel(path)} data row {offset} has "
                    f"no source URL and no source/quality/confidence value"
                )
                continue
            # A derived artefact names its own sources in its preamble, so a row
            # that cites another file in this repository by name is following that
            # declaration rather than failing it.
            if derived and any(u in siblings for u in urls):
                continue
            if derived and not openable:
                # A derived artefact with a stated per-row source column, and
                # some of its rows have not been filled in.
                failures.append(
                    f"[evidence-label] {rel(path)} data row {offset} carries figures "
                    f"and a label, and this file declares itself derived - "
                    f"{contract[0].lstrip('# ').strip()} - but this row's source cell "
                    f"holds {urls[0]!r} rather than a URL, and the column exists for "
                    f"exactly this."
                )
                continue
            if class_i is not None:
                declared = row[class_i].strip()
                if declared and declared != CARRY_MARKER and declared not in EVIDENCE_CLASSES:
                    failures.append(
                        f"[evidence-label] {rel(path)} data row {offset}: "
                        f"evidence_class={declared!r} is outside the vocabulary the root "
                        f"README declares ({' | '.join(sorted(EVIDENCE_CLASSES))}). A "
                        f"class no reader of that table can interpret is not an evidence "
                        f"class; pick one of the declared six, or record the row as "
                        f"{CARRY_MARKER} to say the figure was not re-verified."
                    )
            if derived or openable:
                continue
            if not urls:
                failures.append(
                    f"[evidence-label] {rel(path)} data row {offset} carries figures "
                    f"and a label, but no source. A label is not a source: nobody can "
                    f"re-derive the figure from 'VERIFIED official docs'."
                )
                continue
            failure = (
                f"[evidence-label] {rel(path)} data row {offset} cites {urls[0]!r}, "
                f"which is not a URL a reader can open."
            )
            if contract:
                failures.append(
                    failure.replace(
                        "which is not a URL a reader can open.",
                        "which is not a URL a reader can open. This file's preamble "
                        "declares it a derived artefact whose provenance is the page it "
                        f"regenerates from - {contract[0].lstrip('# ').strip()}",
                    )
                )
            else:
                failures.append(failure)
            if date_cols and not any(row[i].strip() for i in date_cols):
                failures.append(
                    f"[evidence-label] {rel(path)} data row {offset} cites a source "
                    f"but records no access date."
                )


def check_evidence_vocabulary(pass_dir: Path) -> None:
    """Every `evidence_class` cell is a member of the declared set.

    Separate from `evidence-label` because it is a different kind of claim: the
    label check asks whether a row says where its numbers came from, and this one
    asks whether the word it uses for that is one the repository defines. A
    `FIRST-PARTY` cell is not a typo to be tidied; it reads as the strongest class
    in the table while naming a different thing, and that is a stronger claim
    than the data supports.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header or "evidence_class" not in header:
            continue
        i = header.index("evidence_class")
        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) <= i:
                continue
            value = row[i].strip()
            if not value or value in EVIDENCE_CLASSES:
                continue
            declared = " | ".join(sorted(EVIDENCE_CLASSES))
            if value == CARRY_MARKER:
                failures.append(
                    f"[evidence-vocabulary] {rel(path)} data row {offset}: "
                    f"evidence_class={CARRY_MARKER!r} is not one of the declared classes "
                    f"({declared}). It records that the figure was carried forward rather "
                    f"than re-verified, which is a provenance note, not an evidence class."
                )
            elif "," in value or " " in value or "://" in value or "/" in value:
                failures.append(
                    f"[evidence-vocabulary] {rel(path)} data row {offset}: "
                    f"evidence_class={value!r} holds what looks like two values - a URL, "
                    f"a date, or a URL plus a date in the evidence-class column. An "
                    f"arity-preserving column shift puts exactly that there. Reclassify "
                    f"the row into one of the declared classes."
                )
            else:
                failures.append(
                    f"[evidence-vocabulary] {rel(path)} data row {offset}: "
                    f"evidence_class={value!r} is outside the declared set ({declared}). "
                    f"Use one of the declared six, or UNKNOWN when the figure is not "
                    f"published."
                )


def check_dates(pass_dir: Path) -> None:
    today = str(date.today())
    check(pass_dir.name <= today, f"[no-future-pass] {pass_dir.name} is after the machine date {today}")
    log = pass_dir / "data" / "fetch-log.json"
    if pass_dir.name == today and not log.is_file():
        check(
            False,
            f"[fetch-log-corroborates] pass is dated today ({today}) but "
            f"{rel(log)} is absent, so the date cannot be checked",
        )
    if not log.is_file():
        return
    try:
        entries = json.loads(log.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        failures.append(f"[fetch-log-corroborates] {rel(log)} is not valid JSON: {exc}")
        return
    if not isinstance(entries, list) or not entries:
        failures.append(f"[fetch-log-corroborates] {rel(log)} has no entries")
        return
    for entry in entries:
        if not all(k in entry for k in ("url", "http", "sha256")):
            failures.append(
                f"[fetch-log-corroborates] an entry in {rel(log)} is missing "
                f"url/http/sha256, so it cannot be checked against a source"
            )
            return
    sources = pass_dir / "sources"
    if not sources.is_dir():
        return

    # The hash is the point of the log. A recorded SHA-256 that is never
    # recomputed is a string, and a string can be edited without trace; this
    # recomputes every recorded hash against the bytes actually archived.
    #
    # Two forms are compared, because git can change a file's bytes without
    # anyone editing it. With no `.gitattributes` in this repository, a client
    # configured with `core.autocrlf=true` rewrites every LF in a text file to
    # CRLF on checkout, so an archived page's committed bytes are CRLF while the
    # hash recorded at fetch time was taken over LF. Seventeen of the 2026-10-02
    # pass's twenty archived sources are in exactly that state, and every figure
    # read out of them was unverifiable without this second form. A page with no
    # CR byte in it is unaffected, so the normalisation is a fallback rather than
    # a blanket exemption: a mismatch that survives it is a real mismatch.
    crlf = bytes((13, 10))
    lf = bytes((10,))
    for entry in entries:
        saved = entry.get("saved_as")
        if not saved:
            continue
        recorded = str(entry["sha256"]).lower()
        # `saved_as` is written with Windows separators, and the 2026-10-02 log
        # pointed it at `raw/`, the gitignored working directory the fetch was
        # written to rather than at the archive. Resolving by basename inside
        # this pass removes the separator convention from the question and makes
        # a log entry that names the page it archived find it.
        basename = str(saved).replace(chr(92), "/").split("/")[-1]
        candidates = [pass_dir / "sources" / basename,
                      pass_dir / "raw" / basename,
                      pass_dir / basename]
        archived = next((p for p in candidates if p.is_file()), None)
        if archived is None:
            failures.append(
                f"[fetch-log-corroborates] {rel(log)} records {entry.get('url')!r} "
                f"archived as {saved!r}, but no such file exists. The log claims a "
                f"retrieval whose bytes are not in the repository."
            )
            continue
        raw = archived.read_bytes()
        unix_form = raw.replace(crlf, lf)
        as_committed = hashlib.sha256(raw).hexdigest()
        lf_normalised = hashlib.sha256(unix_form).hexdigest()
        if as_committed == recorded:
            form, on_disk = "as committed", len(raw)
        elif lf_normalised == recorded:
            form, on_disk = "LF-normalised", len(unix_form)
        else:
            failures.append(
                f"[fetch-log-corroborates] {rel(archived)} does not hash to the sha256 "
                f"recorded for {entry.get('url')!r}, in either form: recorded "
                f"{recorded}, the committed bytes hash to {as_committed}, and their LF "
                f"normalisation to {lf_normalised}. Either the source moved or the bytes "
                f"were edited after the fetch, and every figure read out of them is now "
                f"unanchored."
            )
            continue
        size = entry.get("bytes")
        if isinstance(size, int) and on_disk != size:
            failures.append(
                f"[fetch-log-corroborates] {rel(archived)} is {on_disk} bytes "
                f"{form}; {rel(log)} recorded {size} for {entry.get('url')!r}."
            )

    # And the other direction: an archived source no log entry accounts for is a
    # page a reader is invited to trust with no record of where it came from.
    logged = {
        str(e.get("saved_as") or "").replace(chr(92), "/").split("/")[-1]
        for e in entries
    }
    for path in sorted(p for p in sources.iterdir() if p.is_file()):
        if path.name not in logged:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            failures.append(
                f"[fetch-log-corroborates] {rel(path)} "
                f"({path.stat().st_size:,} bytes, sha256 {digest[:16]}...) has no entry "
                f"in {rel(log)}. Every archived source records the retrieval that "
                f"produced it: URL, HTTP status, byte count and hash. Add the entry, or "
                f"delete the file and cite nothing to it."
            )


def check_report_matches_data(pass_dir: Path) -> None:
    """A path, a row count or a fetch tally the prose states must match disk.

    Three quantities are compared against the files on disk: a cited `data/`
    path, a row count the prose states for that CSV, and - through
    `_check_fetch_tallies` - the count of retrievals the report states against
    `data/fetch-log.json`. All three are claims a reader cannot check by eye.
    """
    report = pass_dir / "README.md"
    data = pass_dir / "data"
    if not report.is_file() or not data.is_dir():
        return
    text = report.read_text(encoding="utf-8", errors="replace")

    # "N rows", "N-row", "N rows per plan", immediately after a data/ path, and
    # the plainer form where the file is named and "N rows" follows.
    #
    # The third form was added because the first two missed most of a header
    # paragraph. Its citations are `(20 plan x model rows)`, `(6 independent
    # meter readings)` and `(16 SKU lookups ...)`: the count leads and the noun
    # varies, so a pattern keyed on "N rows" matched exactly one of the five
    # citations beside it. Changing "25 model rows" to "24", or "20 plan x model
    # rows" to "21", left the gate at exit 0 with a wrong number in the prose.
    # This one keys on the count itself in the parenthetical that opens right
    # after the path, so the noun does not matter. It is deliberately tighter
    # than the second: it requires the count to be the first thing inside the
    # bracket, which is where this pass writes it, so a number appearing later
    # in a sentence is not read as this file's count.
    patterns = (
        re.compile(r"data/([A-Za-z0-9._-]+\.csv)\)?\s*\((\d+)[- ]row", re.IGNORECASE),
        re.compile(r"data/([A-Za-z0-9._-]+\.csv)\b[^.\n]{0,40}?\b(\d+)\s+rows?\b",
                   re.IGNORECASE),
        re.compile(r"data/([A-Za-z0-9._-]+\.csv)\)?\s*\(\s*(\d+)\b", re.IGNORECASE),
    )
    for pattern in patterns:
        for match in pattern.finditer(text):
            name, claimed = match.group(1), int(match.group(2))
            path = data / name
            if not path.is_file():
                failures.append(
                    f"[report-matches-data] {rel(report)} cites data/{name} but it is "
                    f"not in {rel(data)}/"
                )
                continue
            _, rows = read_rows(path)
            actual = len(data_rows(rows))
            if actual != claimed:
                failures.append(
                    f"[report-matches-data] {rel(report)} says data/{name} has "
                    f"{claimed} rows, it has {actual}"
                )

    # A `data/<pass>/data/<name>.csv` path is wrong unless that pass holds that file.
    for match in re.finditer(r"data/(\d{4}-\d{2}-\d{2})/data/([A-Za-z0-9._-]+\.csv)", text):
        other, name = match.group(1), match.group(2)
        if not (ROOT / other / "data" / name).is_file():
            failures.append(
                f"[report-matches-data] {rel(report)} cites data/{other}/data/{name}, "
                f"which does not exist. The pass is {pass_dir.name} and it holds no "
                f"{name}."
            )

    # Any other data/<name>.csv the report names must be in this pass's data/, or
    # in another pass's - a cross-pass citation names the other pass explicitly,
    # and that is a path a reader can open.
    citation = re.compile(
        r"(?:(?:\.\./)?(\d{4}-\d{2}-\d{2})/)?data/([A-Za-z0-9._-]+\.csv)"
    )
    for match in citation.finditer(text):
        other, name = match.group(1), match.group(2)
        target = ROOT / other / "data" / name if other else data / name
        if target.is_file():
            continue
        where = rel(ROOT / other / "data") if other else rel(data)
        failures.append(
            f"[report-matches-data] {rel(report)} cites data/{name} but it is not "
            f"in {where}/"
        )

    _check_fetch_tallies(pass_dir, report, text)


def _fetch_tallies(pass_dir: Path) -> dict[str, int] | None:
    """The log's own counts, or None when this pass keeps no fetch log.

    `entries` is every recorded retrieval, `ok` the subset that returned HTTP 200,
    `archived` the distinct files the log says it wrote and `on_disk` the sources
    actually committed. The four are different quantities and the gap between
    `entries` and `archived` is the interesting one: re-fetching a page whose
    bytes came back unchanged records a retrieval without archiving a second copy,
    so a report that says "twelve fetches" and "ten distinct results" can be
    right on both and still read as a contradiction.
    """
    log = pass_dir / "data" / "fetch-log.json"
    if not log.is_file():
        return None
    try:
        entries = json.loads(log.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None
    if not isinstance(entries, list):
        return None
    sources = pass_dir / "sources"
    return {
        "entries": len(entries),
        "ok": sum(1 for e in entries if str(e.get("http")) == "200"),
        "archived": len({str(e.get("saved_as") or "").replace(chr(92), "/").split("/")[-1]
                         for e in entries if e.get("saved_as")}),
        "on_disk": len([p for p in sources.iterdir() if p.is_file()]) if sources.is_dir() else 0,
    }


def _check_fetch_tallies(pass_dir: Path, report: Path, text: str) -> None:
    """A report's count of its own retrievals must be the log's count.

    The row-count check above compares the report against the CSVs. Nothing
    compared it against `fetch-log.json`, so "Eleven fetches ... 11/11 returned
    200, and the nine distinct results are archived" survived against a log
    holding twelve entries and ten archived files — three wrong numbers, none of
    them near a CSV.

    Three forms are matched, because the counts appear in three grammatical
    positions and a check that reads only one of them reads none of the two
    others:

    * `N/M returned 200`, or the `all N` it is written as when the report says
      every attempt succeeded;
    * `N fetches`, and the spelled-out form;
    * `the N distinct results are archived`.

    A count is only checked in a position whose tally exists, so a pass that
    keeps no fetch log is not asked about numbers it never claimed.
    """
    tallies = _fetch_tallies(pass_dir)
    if tallies is None:
        return
    spelled = "|".join(
        sorted((w for w in NUM_WORDS if 1 <= NUM_WORDS[w] <= 99), key=len, reverse=True)
    )
    token = rf"(\d+|{spelled})"

    def as_int(raw: str) -> int | None:
        raw = raw.strip().lower()
        return int(raw) if raw.isdigit() else NUM_WORDS.get(raw)

    def claimed(match: re.Match, group: int = 1) -> int | None:
        return as_int(match.group(group))

    where = rel(report)

    def fail(position: str, said: int, actual: int) -> None:
        failures.append(
            f"[report-matches-data] {where} says {position} is {said}, "
            f"data/fetch-log.json records {actual}"
        )

    # "11/11 returned 200" - the numerator is the successes and the denominator
    # is the attempts, and both are claims about the same list.
    for match in re.finditer(rf"{token}\s*/\s*{token}\s+returned\s+200", text, re.IGNORECASE):
        numerator, denominator = claimed(match), claimed(match, 2)
        if numerator is not None and numerator != tallies["ok"]:
            fail("the number of fetches that returned 200", numerator, tallies["ok"])
        if denominator is not None and denominator != tallies["entries"]:
            fail("the number of fetches", denominator, tallies["entries"])

    # "all twelve fetches"
    for match in re.finditer(rf"all\s+{token}\s+fetches\b", text, re.IGNORECASE):
        said = claimed(match)
        if said is not None and said != tallies["entries"]:
            fail("the number of fetches", said, tallies["entries"])

    # "the nine distinct results are archived"
    for match in re.finditer(
            rf"{token}\s+distinct\s+(?:results?|sources?|pages?|files?)\s+are\s+archived",
            text, re.IGNORECASE):
        said = claimed(match)
        if said is not None and said != tallies["archived"]:
            fail("the number of distinct results archived", said, tallies["archived"])

    # A bare "20 first-party sources fetched serially", which is the form the
    # 2026-10-02 pass uses.
    for match in re.finditer(
            rf"\b{token}\s+(?:first-party\s+)?(?:fetches|sources)\s+fetched\b",
            text, re.IGNORECASE):
        said = claimed(match)
        if said is not None and said != tallies["entries"]:
            fail("the number of fetches", said, tallies["entries"])


def check_model_slug_joins(pass_dir: Path) -> None:
    """A plan row that names a model must join to a row in the model database.

    The plan table carries display names ("GLM-5.3-Flash") and the model
    database carries slugs ("glm-5-3-flash"). Joining them on the display name
    silently yields an empty ranking: the first version of this pass's ranked
    table was empty for exactly that reason and said nothing was wrong. A row
    whose model has no counterpart is therefore an error, not a gap.

    The one legitimate exception is a SKU the leaderboard does not carry at all,
    and it has to be said so rather than inferred: a row whose
    `aa_score_provenance` cell begins `unscored:` is declaring that the leaderboard
    has no row for it. Skipping those is not a loophole, because `unscored-model`
    requires the marker to be present whenever the score cannot be joined, so
    marking the absence is the only way through, and an unmarked mismatch still
    fails here.
    """
    data = pass_dir / "data"
    models = data / "models-database.csv"
    plans = data / "plan-economics.csv"
    if not models.is_file() or not plans.is_file():
        return
    mheader, mrows = read_rows(models)
    pheader, prows = read_rows(plans)
    if "slug" not in mheader or "model_slug" not in pheader:
        return
    mi = mheader.index("slug")
    pi = pheader.index("model_slug")
    pi_prov = pheader.index("aa_score_provenance") if "aa_score_provenance" in pheader else None
    known = {r[mi].strip() for r in data_rows(mrows) if len(r) > mi}
    for offset, row in enumerate(data_rows(prows), start=1):
        if len(row) <= pi:
            continue
        slug = row[pi].strip()
        if not slug or slug == "UNKNOWN":
            continue
        if slug in known:
            continue
        prov = row[pi_prov].strip().lower() if pi_prov is not None and len(row) > pi_prov else ""
        if prov.startswith("unscored:"):
            continue
        failures.append(
            f"[model-slug-joins] {rel(plans)} data row {offset} names model_slug "
            f"{slug!r}, which is not in data/models-database.csv and is not marked "
            f"unscored: in aa_score_provenance"
        )


def check_ladder_prices_on_page(pass_dir: Path) -> None:
    """A ladder price must appear in the bytes of the page it cites.

    The plan ladder records, per row, which archived page the figure was read
    from. Verifying each price against that page found four of thirty rows whose
    cited page does not contain the price: Z.ai's overview page publishes only
    "starting at just 18 USD", so the Pro and Max prices attributed to it came
    from an earlier pass. A price with the wrong provenance is worse than a
    missing one, because it looks sourced.

    A page that publishes no dollar figure at all cannot be checked against a
    dollar figure, and pretending otherwise produces a check that passes for the
    wrong reason. `Kilo Individual` is the live case: its row records a price of
    0, `kilo-home.html` carries three bare `0`s and no price at all, and the check
    reported success because the digit matched. A price of exactly zero is
    reported as FREE-ON-PAGE instead, which is a claim about the page rather than
    about a digit appearing somewhere in it.
    """
    ladder = pass_dir / "data" / "plan-ladder.csv"
    sources = pass_dir / "sources"
    if not ladder.is_file() or not sources.is_dir():
        return
    header, rows = read_rows(ladder)
    if "vendor_source" not in header or "price_value" not in header:
        return
    src_i, price_i = header.index("vendor_source"), header.index("price_value")
    ext_i = header.index("extraction") if "extraction" in header else None
    plan_i = header.index("plan") if "plan" in header else None

    money_on_page: dict[str, set[str]] = {}
    for path in sorted(p for p in sources.iterdir() if p.is_file()):
        text = path.read_text(encoding="utf-8", errors="replace")
        # Normalise thousands separators and the ".00" a page may or may not
        # print, so $1,200 and 1200 and 1200.00 compare equal. Three forms are
        # collected because a vendor writes its price three ways: "$18" in prose,
        # "18 USD" in a sentence, and "price":18 in a JSON-LD Offer block.
        # Checking only the first reports correct rows as missing, which is a
        # false positive that trains a reader to ignore the check.
        found = set()

        def add(token: str) -> None:
            token = token.replace(",", "").strip()
            if token:
                found.add(token.rstrip("0").rstrip(".") if "." in token else token)

        for token in re.findall(r"\$\s?([\d,]+(?:\.\d+)?)", text):
            add(token)
        for token in re.findall(r"(\d+(?:\.\d+)?)\s*(?:USD|dollars)\b", text):
            add(token)
        for token in re.findall(r'"price"\s*:\s*"?([\d.]+)"?', text):
            add(token)
        money_on_page[path.name] = found

    for offset, row in enumerate(data_rows(rows), start=1):
        if len(row) <= max(src_i, price_i):
            continue
        page, price = row[src_i].strip(), row[price_i].strip()
        if not price or price == "UNKNOWN" or not page:
            continue
        if ext_i is not None and len(row) > ext_i and row[ext_i].strip() in (
            "NOT-ON-PAGE", "NOT-PUBLISHED", "CARRIED-FORWARD", "FREE-ON-PAGE",
        ):
            continue
        plan = row[plan_i].strip() if plan_i is not None and len(row) > plan_i else "the plan"
        # Normalise the same way `add` does: strip a trailing ".00", not every
        # trailing zero. `rstrip("0")` on "10" yields "1", which reports a price
        # the page plainly contains as missing.
        norm = price.replace(",", "").strip()
        if "." in norm:
            norm = norm.rstrip("0").rstrip(".")
        if norm == "0":
            failures.append(
                f"[ladder-price-on-page] {rel(ladder)} data row {offset}: the row prices "
                f"{plan!r} at 0 and attributes it to sources/{page}. A zero cannot be "
                f"found or missed on a page - it is present everywhere a bare digit "
                f"appears. Mark the row FREE-ON-PAGE if the plan is free, or "
                f"NOT-PUBLISHED if the page states no price, so the cell records which."
            )
            continue
        if norm not in money_on_page.get(page, set()):
            failures.append(
                f"[ladder-price-on-page] {rel(ladder)} data row {offset}: {price} is attributed to "
                f"sources/{page}, which does not contain that figure. Re-read the page, or mark the "
                f"row NOT-ON-PAGE / CARRIED-FORWARD."
            )


# --- the 2026-10-06 checks -------------------------------------------------
#
# Each of the four below was written after a specific defect reached a published
# verdict, and each is demonstrated twice in docs/reviews-2026-10-06.md: once
# against a planted defect, once against the corrected data. A check that has
# only been seen failing is indistinguishable from a check that cannot pass.


def _money_on_page(text: str) -> set[str]:
    """Every money figure a page carries, normalised for comparison.

    A vendor writes the same price several ways: "$18" in prose, "18 USD" in a
    sentence, and `"price":18` in a JSON-LD Offer block, and a price of $10 may
    be printed as 10, 10.0 or 10.00. Checking only the first form reports correct
    figures as missing, which is a false positive that trains a reader to ignore
    the check, so all three forms are collected and normalised the same way.
    """
    found: set[str] = set()

    def add(token: str) -> None:
        token = token.replace(",", "").strip()
        if token:
            found.add(token.rstrip("0").rstrip(".") if "." in token else token)

    for token in re.findall(r"\$\s?([\d,]+(?:\.\d+)?)", text):
        add(token)
    for token in re.findall(r"(\d+(?:\.\d+)?)\s*(?:USD|dollars)\b", text):
        add(token)
    for token in re.findall(r'"price"\s*:\s*"?([\d.]+)"?', text):
        add(token)
    return found


def _normalise_money(value: str) -> str:
    norm = value.replace(",", "").strip()
    return norm.rstrip("0").rstrip(".") if "." in norm else norm


# An entry whose dollar figures are the superseded ones being *recorded*. A
# correction is documented, not deleted, and a blanket "the entry carries a
# CORRECTED marker, stop checking" turns one recorded figure into an exemption for
# the rest of the entry. Only the lines that record the superseded quotation are
# exempt, and only while the recording is open.
CORRECTED_OPEN = re.compile(r"\*\*CORRECTED\s+\d{4}-\d{2}-\d{2}")
CORRECTED_CLOSE = re.compile(r"\*\*[A-Z][^*]{2,60}\*\*")


def check_quoted_money_on_page(pass_dir: Path) -> None:
    """A money figure quoted in references/*.md must be on the page it cites.

    `ladder-price-on-page` above does this for the plan-ladder CSV, and it found
    four rows whose cited page did not contain the price. It returns early unless
    `data/plan-ladder.csv` exists, and only the 2026-10-02 pass has one, so the
    check never touched the pass that needed it.

    The defect this was written for is worse than a missing price. 2026-10-06's
    references file quoted the DeepSeek price table as "off-peak $0.007 cache
    hit / $0.22 input miss / $0.66 output; peak $0.014 / $0.44 / $1.32". Four of
    those six figures are not on the page, and they propagated into a blended
    rate, two cost-per-10B figures, two multipliers and the relay ratio. A
    fabricated quotation is indistinguishable from a real one in the file it sits
    in, so the only defence is comparing the quoted figure against the archived
    bytes.

    Two properties of the scoping were wrong in the first version.

    * **Attribution.** An entry carries its money figures on the lines below the
      line that names its archived page - that is how a transcription block is
      written - so the page is attributed to the whole entry, from its `**[Rn]**`
      marker to the next marker or the next heading. Any other form attaches the
      page to every figure in the file, including the figures of an entry that
      names no page at all: the two community meters, quoted from an archived feed
      that carries no dollar figures, were being checked against a vendor's
      pricing page, and would have been reported as fabricated quotations.
    * **Correction scope.** A dated `**CORRECTED …**` marker exempts the lines
      that record the superseded quotation and nothing else. Exempting the rest of
      the entry made a corrected entry uncheckable, which is the one entry class
      whose whole purpose is to be corrected.
    """
    references = pass_dir / "references"
    sources = pass_dir / "sources"
    if not references.is_dir() or not sources.is_dir():
        return

    pages: dict[str, set[str]] = {}
    for path in sorted(p for p in sources.iterdir() if p.is_file()):
        pages[path.name] = _money_on_page(
            path.read_text(encoding="utf-8", errors="replace")
        )

    # A money figure derived by dividing two published numbers is not on the
    # page and is not expected to be; a per-1M rate blended from a table, or a
    # per-token rate restated per 1M, is the same. Those are checked by
    # arithmetic elsewhere, not here.
    #
    # Narrowed 2026-10-07. This used to skip any line containing `per 1m`, `/m`,
    # `blended`, `per mtok`, `per month x` or `x 4.33`. Those are six loose
    # keywords and they were an escape hatch: a fabricated figure written as
    # "billed $0.007 per 1M cache hits" carried `per 1m` and passed silently,
    # because a keyword anywhere on the line silenced every figure on it. The
    # keywords that survive are the ones that *show the arithmetic* rather than
    # name a unit - a blend, a per-token restatement, a spelled-out division.
    # A unit label on its own ("per 1M", "$/M", "blended $/Mtok") no longer
    # exempts anything, so a figure that merely sits next to one is checked
    # against the page like any other.
    #
    # The test is applied to the figure's whole sentence, not to the physical
    # line. Wrapped prose splits a derivation across lines - "blends to
    # $0.00966 per 1M and the peak / tariff to $0.01932 per 1M" - and a
    # line-local test would check the continuation and reject a correct figure.
    derived_markers = (
        "blends to", "blended to", "blend of", "which blends",
        "per token", "times 1m", "x 1m", "÷ 1m",
    )

    def derived_sentence(text: str, start: int) -> str:
        """The sentence holding the character at `start`, so a wrapped
        derivation is judged as one sentence rather than as several lines.

        A period only ends a sentence when it is a real terminator: not the
        dot in a decimal (`0.00966`), not the dot in an abbreviation
        (`i.e.`, `e.g.`, `etc.`, `vs.`), and not one inside a filename.
        Without that, "1.6e-08 per token, i.e. $0.80 / $3.20 per 1M" was cut
        after "i." and the derivation that introduces it was lost.
        """
        def is_break(pos: int) -> bool:
            if text[pos] != ".":
                return False
            before = text[max(0, pos - 4):pos].lower()
            if before.endswith(("e.g", "i.e", "etc", "vs", "cf")):
                return False
            if pos + 1 < len(text) and text[pos + 1].isdigit():
                return False  # a decimal, not a terminator
            return pos + 1 >= len(text) or text[pos + 1].isspace()

        left = max((p for p in range(start - 1, -1, -1) if is_break(p)), default=-1)
        right = next((p for p in range(start, len(text)) if is_break(p)), None)
        if right is None:
            right = min(len(text), start + 200)
        return text[left + 1:right]

    for path in sorted(references.glob("*.md")):
        text = path.read_text(encoding="utf-8", errors="replace")
        # Split the file into entries. An entry runs from its `**[Rn]` marker to
        # the next marker or the next heading, whichever comes first, so an entry
        # cannot inherit the page of a heading it sits under.
        for part in re.split(r"(?m)^(?=\*\*\[R\d+\])", text):
            body = part.split("\n\n")[0]
            named = re.search(r"\(\.\./sources/([^)]+)\)", body)
            if not named:
                continue
            page = named.group(1)
            on_page = pages.get(page)
            if on_page is None:
                continue
            first_line = part.splitlines()[0] if part.splitlines() else ""
            recording = False
            cursor = 0
            for offset, line in enumerate(part.splitlines(), start=1):
                line_at = cursor
                cursor += len(line) + 1
                if not line.strip():
                    recording = False
                    continue
                if CORRECTED_OPEN.search(line):
                    recording = True
                    continue
                if recording:
                    if not CORRECTED_CLOSE.search(line):
                        # Still inside the recording: the superseded figure.
                        continue
                    recording = False
                for match in re.finditer(r"\$\s?(\d[\d,]*\.?\d*)", line):
                    token = match.group(1)
                    if _normalise_money(token) in on_page:
                        continue
                    sentence = derived_sentence(part, line_at + match.start())
                    if any(marker in sentence.lower() for marker in derived_markers):
                        continue
                    failures.append(
                        f"[quoted-money-on-page] {rel(path)} entry "
                        f"{first_line[:60]!r} quotes ${token}, which is not on "
                        f"sources/{page}, the page this entry cites. A quotation that is "
                        f"not in the source is not evidence; re-read the page, show the "
                        f"derivation that produces the figure, or put the superseded figure "
                        f"inside a dated CORRECTED recording."
                    )


def check_provenance_in_log(pass_dir: Path) -> None:
    """A provenance string may not assert a dated reading the log does not record.

    The defect this was written for is in the pass it ships with. Repairing a
    fabricated quotation required writing down where the corrected figure came
    from, and the provenance cell added to settle it asserted a leaderboard lookup
    at a score and on a date that no fetch log entry records. It was fabricated in
    exactly the same way as the quotation it was written to fix: by asserting a
    retrieval that had not happened.

    The rule is narrow on purpose. A provenance string may claim a dated reading
    only if a log entry exists that puts the subject on the record with a read
    date on or before the date claimed. Nothing here decides whether the reading
    should have happened; it decides only that the repository's own record of
    retrievals has to contain it.

    A provenance string is `kind:subject-on-YYYY-MM-DD`, or one of two things
    that assert no retrieval:

    * `unscored:<reason>` - the leaderboard has no row for this SKU. Validated by
      `unscored-model`, which requires the marker to be the only way past a row
      whose score cannot be joined, so it cannot be used to smuggle a borrowed
      score past anything.
    * `UNKNOWN` - nothing is claimed. Accepted as an answer, never as evidence.

    `subject` names what was read: a URL path, an archived file, or a slug. It has
    to match a retrieval the log records.
    """
    log_path = pass_dir / "data" / "fetch-log.json"
    data = pass_dir / "data"
    if not data.is_dir():
        return
    date_re = re.compile(r"(\d{4}-\d{2}-\d{2})")
    reads: list[tuple[str, str]] = []
    if log_path.is_file():
        try:
            entries = json.loads(log_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            entries = []
        for entry in entries if isinstance(entries, list) else []:
            url = str(entry.get("url") or "")
            when = str(entry.get("read_date") or pass_dir.name)
            saved = str(entry.get("saved_as") or "")
            if url:
                # The archived page's own name is part of the provenance of a
                # reading taken out of it: the leaderboard payload is archived as
                # `aa-models.html`, so a score read out of it is corroborated by
                # the file the bytes came from.
                reads.append((url + " " + saved.replace(chr(92), "/"), when))
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        for column in ("aa_score_provenance", "score_provenance", "provenance"):
            if column not in header:
                continue
            i = header.index(column)
            for offset, row in enumerate(data_rows(rows), start=1):
                if len(row) <= i:
                    continue
                value = row[i].strip()
                if not value or value.upper() == "UNKNOWN":
                    continue
                kind, _, rest = value.partition(":")
                if not rest:
                    failures.append(
                        f"[provenance-in-log] {rel(path)} data row {offset}: "
                        f"{column}={value!r} does not say what kind of reading it "
                        f"records. The form is 'kind:subject-on-YYYY-MM-DD', or "
                        f"'unscored:<reason>' when there is no score."
                    )
                    continue
                if kind.strip().lower().startswith("unscored"):
                    continue
                # A provenance may name a second kind: `scored:leaderboard:<page>`.
                # The kinds are the vocabulary; the subject is what is left, and it
                # keeps its own `leaderboard:` prefix, so it can contain a colon.
                rest = rest.strip()
                prefix, _, remainder = rest.partition(":")
                if prefix.strip().lower() in PROVENANCE_KINDS and remainder.strip():
                    rest = remainder.strip()
                # `kind:subject-on-YYYY-MM-DD`. The date is the last one, so it
                # is stripped from the right.
                subject = rest
                claimed = None
                for match in date_re.finditer(subject):
                    claimed = match
                if claimed and not subject[claimed.end():].strip():
                    subject = subject[: claimed.start()].strip().rstrip("-")
                    if subject.endswith("-on"):
                        subject = subject[:-3]
                if not claimed or not subject:
                    failures.append(
                        f"[provenance-in-log] {rel(path)} data row {offset}: "
                        f"{column}={value!r} asserts a reading without saying when it "
                        f"was taken. An undated provenance cannot be checked against a "
                        f"fetch log and is not one."
                    )
                    continue
                when = claimed.group(1)

                def records(entry: str, read_on: str) -> bool:
                    """Does this logged retrieval put the subject on the record?

                    Two ways. The subject appears in the URL, which is the case for
                    a per-model page. Or the subject appears in the name of the
                    archived file the bytes were saved to, which is the case for a
                    payload the reader extracted the figure from.

                    The second rule is why the subject of a leaderboard score is
                    the archived page's name rather than the slug: the slug is the
                    row's `model_slug`, and the page is what the log can vouch for.
                    """
                    if read_on > when:
                        return False
                    lowered = entry.lower()
                    if subject in lowered or subject in lowered.replace("/", "-"):
                        return True
                    return False

                if any(records(entry, read_on) for entry, read_on in reads):
                    continue
                where = rel(log_path) if log_path.is_file() else "the fetch log"
                failures.append(
                    f"[provenance-in-log] {rel(path)} data row {offset}: "
                    f"{column}={value!r} asserts that {subject!r} was read on or before "
                    f"{when}, and {where} records no such retrieval. A provenance string "
                    f"that names a reading the repository does not record is an "
                    f"assertion, not a provenance. Add the fetch, or write "
                    f"'unscored:<reason>'."
                )


# A token column's own unit, so a value can be checked against its header rather
# than against a guess. `tokens` with no suffix is taken as raw tokens, which is
# the one convention that makes the stored-row comparison meaningful.
TOKEN_COLUMN_UNITS = {
    "monthly_tokens": 1,
    "monthly_tokens_m": 1e6,
    "tokens_m_advertised": 1e6,
    "tokens_m_converted": 1e6,
    "tokens": 1,
    "tokens_m": 1e6,
    "tokens_m_at_ceiling": 1e6,
    "plan_monthly_tokens": 1,
    "monthly_yi": 1e8,
    "monthly_yi_value": 1e8,
}

# Any token-bearing column is matched against this list, and one that is not on
# it is refused rather than skipped. The first version compared only enumerated
# pairs, which meant (a) a file with a single token column could not be checked at
# all - the common case, and the shape the yi defect had - and (b) a column called
# `monthly_tokens_b` carrying an 11.029-vs-11029 error passed silently, because
# the check had never heard of it. An unknown unit column is a column whose
# header makes no promise about scale, and that is the ambiguity this check
# exists to resolve rather than pass over.
TOKEN_COLUMN_PATTERN = re.compile(r"^(monthly_|plan_monthly_)?tokens|token_|_(tokens|token)$|tokens_")

# Columns that state the SAME quantity under different units, compared by default.
# Only column pairs listed here are checked against each other, because "any two
# token columns must agree" is wrong in general: `tokens_m_advertised` and
# `tokens_m_measured` are two different quantities on purpose (a vendor ceiling
# and a user meter), and treating them as one produced a false positive on
# correct data when this check was first written. A check that is confidently
# wrong is worse than no check.
SAME_QUANTITY_GROUPS = (
    frozenset({"monthly_tokens", "monthly_tokens_m"}),
    frozenset({"monthly_tokens", "tokens_m"}),
    frozenset({"monthly_tokens_m", "tokens_m"}),
    frozenset({"monthly_tokens_m", "tokens_m_at_ceiling"}),
    frozenset({"tokens_m_advertised", "monthly_tokens"}),
    frozenset({"tokens_m_advertised", "monthly_tokens_m"}),
    frozenset({"tokens_m_advertised", "tokens_m"}),
    frozenset({"tokens_m_advertised", "monthly_yi"}),
    frozenset({"tokens_m_converted", "monthly_tokens_m"}),
    frozenset({"monthly_tokens_m", "monthly_yi"}),
    frozenset({"tokens_m", "monthly_yi"}),
    frozenset({"plan_monthly_tokens", "monthly_yi"}),
    frozenset({"monthly_yi", "monthly_yi_value"}),
)

# A column whose name carries this suffix is a deliberately different quantity and
# is excluded from the comparison above. `tokens_m_measured` is one: it is a user
# meter reading, not the vendor ceiling in the adjacent column, and the two are
# expected to disagree by a large factor.
DIFFERENT_QUANTITY_SUFFIX = "_measured"

# A token column carrying a magnitude letter in its own name states that letter's
# power of ten. `monthly_tokens_b` is billions, `monthly_tokens_m` millions,
# `monthly_tokens_k` thousands. This is what makes a single-column file
# checkable: the header itself carries the unit, so a value can be read against
# it without a second column to compare against.
NAME_SUFFIX_UNITS = {"k": 1e3, "m": 1e6, "b": 1e9, "bn": 1e9, "g": 1e9, "t": 1e12}

# Below this, a token count is not a token count, and above this it is larger
# than any monthly allowance published in this market. Both ends are the same
# error: a count that arrived multiplied or divided by a power of ten. The lower
# end was checked and the upper end was not, which is the defect's own direction
# - yi is 10^8, so reading 25.81 yi as 25.81 billion overstates by a factor of
# ten - so a check that only looked for understatement could not see the thing it
# was written for.
#
# The bounds come from this repository's own data rather than from a general
# notion of what a lot of tokens is: the largest monthly allowance any archived
# vendor page in this repository publishes is 22,059M, five orders of magnitude
# below the upper bound.
MIN_PLAUSIBLE_MONTHLY_TOKENS = 1e6
MAX_PLAUSIBLE_MONTHLY_TOKENS = 1e13


def _declared_unit_from_name(name: str) -> float | None:
    """The multiplier a column name's trailing unit letter declares, if any.

    A compound name like `monthly_tokens_m_converted` declares its unit in the
    middle rather than at the end, so the token stem is located first and the
    letter immediately after it is read.
    """
    tail = name.rsplit("_", 1)
    if len(tail) == 2 and tail[1].lower() in NAME_SUFFIX_UNITS:
        return NAME_SUFFIX_UNITS[tail[1].lower()]
    stem = re.search(r"tokens?_([a-z]+)", name)
    if stem:
        return NAME_SUFFIX_UNITS.get(stem.group(1))
    return None


def _parse_token_value(raw: str):
    """A token count as a float, or None. Accepts CJK magnitude suffixes."""
    text = raw.strip().replace(",", "")
    if not text or text.upper() == "UNKNOWN":
        return None
    scale = 1.0
    for suffix, factor in CJK_SCALE.items():
        if text.endswith(suffix):
            scale = factor
            text = text[: -len(suffix)].strip()
            break
    try:
        return float(text) * scale
    except ValueError:
        return None


def _check_single_token_column(path: Path, offset: int, name: str, raw: str,
                               unit: float | None) -> None:
    """A lone token column is checked against the unit its own header declares.

    The pair comparison below needs two columns to exist, so a file with one token
    column was unchecked - and one token column is the common case, and the shape
    the yi defect actually had. The column's own unit is applied first, so
    `tokens_m_at_ceiling=1697` is 1.697 billion tokens and is not an error, while
    a `monthly_tokens_m_converted` cell reading 0.453 is 453,000 tokens and is.

    A value whose magnitude cannot be a monthly allowance is a count that arrived
    divided or multiplied by a power of ten. In this market a monthly allowance
    runs from ~34M (Kimi K3 at a $15 cap) to ~22,059M, so neither end of the
    plausible band is near.
    """
    value = _parse_token_value(raw)
    if value is None:
        return
    if unit is None:
        failures.append(
            f"[unit-scale] {rel(path)} data row {offset}: column {name!r} holds a "
            f"token count but its header declares no unit, so {raw.strip()} cannot "
            f"be read against anything. Name the unit in the column "
            f"(tokens_m, monthly_tokens, monthly_tokens_b) or give it a companion "
            f"column in a stated unit."
        )
        return
    tokens = value * unit
    if 0 < tokens < MIN_PLAUSIBLE_MONTHLY_TOKENS:
        failures.append(
            f"[unit-scale] {rel(path)} data row {offset}: {name}={raw.strip()} is "
            f"{tokens:,.0f} tokens in that column's unit. No monthly token "
            f"allowance in this market is below "
            f"{MIN_PLAUSIBLE_MONTHLY_TOKENS:,.0f}, so this is a magnitude error "
            f"rather than a small figure. A count that arrived divided by a power "
            f"of ten on the way in produces exactly this."
        )
    elif tokens > MAX_PLAUSIBLE_MONTHLY_TOKENS:
        failures.append(
            f"[unit-scale] {rel(path)} data row {offset}: {name}={raw.strip()} is "
            f"{tokens:,.0f} tokens in that column's unit. No monthly token allowance "
            f"published in this market is above {MAX_PLAUSIBLE_MONTHLY_TOKENS:,.0f}, "
            f"so this is a magnitude error rather than a large figure - and "
            f"overstatement is the direction the original defect went in, because a "
            f"CJK magnitude suffix is 10^8 and 25.81 of them is 2,581,000,000, not "
            f"25.81 billion. A count that arrived multiplied rather than divided by "
            f"a power of ten produces exactly this."
        )


def check_unit_scale(pass_dir: Path) -> None:
    """Two columns stating one quantity must agree once each is read in its unit.

    A source row stored `monthly_tokens: 2581000000` and, alongside it, a
    human-readable `25.81` under a `monthly_yi` header. yi is 10^8, so those two
    cells agree and describe 2.58 billion. Reading the second cell as 25.81 billion
    is a 10x error; it survived a reconciler and flipped a HIT only when a second
    reconciler re-checked the arithmetic against the stored row. This check is
    that re-check made structural.

    Only column pairs listed in SAME_QUANTITY_GROUPS are compared. The first
    version compared every token column against every other and reported the
    correct `tokens_m_advertised=6211` / `tokens_m_measured=2900` row as a 2.1x
    magnitude error, because those two columns are deliberately different
    quantities: one is a vendor ceiling and the other a user meter. A check that
    is confidently wrong is worse than no check.

    That restraint then over-corrected: pair comparison alone cannot fire on a
    file with a single token column, which is the common case and the shape the yi
    defect actually had, and it silently passed a `monthly_tokens_b` column
    carrying an 11.029-vs-11029 error because the column was not on the list. So
    every token-bearing column is now also checked on its own against the unit
    its header declares and against what a monthly allowance can physically be -
    at both ends, because the original defect was an overstatement.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        index = {name.strip().lower(): i for i, name in enumerate(header)}
        present_names = {
            name for name in index
            if name in TOKEN_COLUMN_UNITS and not name.endswith(DIFFERENT_QUANTITY_SUFFIX)
        }
        # Every column that looks like a token count, whether or not the check has
        # seen it before. An unrecognised unit column is the case the old
        # enumerated-pairs version could not reach, so a column whose name
        # declares a magnitude letter gets that letter as its unit.
        token_like = {}
        for name in index:
            if name in present_names or name.endswith(DIFFERENT_QUANTITY_SUFFIX):
                continue
            if not TOKEN_COLUMN_PATTERN.match(name):
                continue
            token_like[name] = _declared_unit_from_name(name)
        pairs = [
            (a, b) for group in SAME_QUANTITY_GROUPS
            for a, b in [sorted(group)]
            if a in present_names and b in present_names
        ]
        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) != len(header):
                continue
            for name in sorted(present_names):
                if len(row) <= index[name]:
                    continue
                _check_single_token_column(
                    path, offset, name, row[index[name]], TOKEN_COLUMN_UNITS[name]
                )
            for name, unit in sorted(token_like.items()):
                if len(row) <= index[name]:
                    continue
                _check_single_token_column(path, offset, name, row[index[name]], unit)
            for a_name, b_name in pairs:
                a_raw = _parse_token_value(row[index[a_name]])
                b_raw = _parse_token_value(row[index[b_name]])
                if a_raw is None or b_raw is None:
                    continue
                # Each cell as written, then as tokens under its own column unit.
                a_tok = a_raw * TOKEN_COLUMN_UNITS[a_name]
                b_tok = b_raw * TOKEN_COLUMN_UNITS[b_name]
                if not a_tok or not b_tok:
                    continue
                ratio = max(a_tok, b_tok) / min(a_tok, b_tok)
                # One quantity in two units, so anything past 2x is a unit or
                # magnitude disagreement rather than rounding.
                if ratio > 2.0:
                    failures.append(
                        f"[unit-scale] {rel(path)} data row {offset}: {a_name}='{row[index[a_name]].strip()}' "
                        f"is {a_tok:,.0f} tokens and {b_name}='{row[index[b_name]].strip()}' is "
                        f"{b_tok:,.0f} tokens. Both columns state the same quantity and they "
                        f"differ by {ratio:.1f}x. A CJK magnitude suffix (wan/yi/zhao, "
                        f"10^4/10^8/10^12) copied instead of converted produces exactly this."
                    )


def _normalise_identity(text: str) -> str:
    """Fold a display name or slug to comparable form.

    "Muse Spark 1.3 Contributor" and "muse-spark-1-3" are the same underlying
    model; "Muse Spark 1.3 Contributor" and "muse-spark-1-3-contributor" are
    different SKUs of it. That difference is the whole defect, so tier words are
    kept as separate tokens rather than normalised away.
    """
    text = text.lower().replace("-", " ").replace("_", " ")
    text = re.sub(r"\(.*?\)", " ", text)
    text = re.sub(r"[^a-z0-9 ]+", " ", text)
    return " ".join(text.split())


# Words that qualify a model into a different SKU rather than naming it. A plan
# row selling one of these is not selling the row it joined to.
SKU_TIER_WORDS = ("contributor", "pro", "max", "lite", "mini", "flash", "preview")

# A displayed name that deliberately carries no SKU tier. The plan names a
# vendor's own model row; the landscape may name the same row by its base product
# name, and reading one of these as a tier is reading a measurement variation
# ("Preview"), a vendor's own marketing word for a mode ("Max Effort", "Adaptive
# Reasoning"), or a brand used for two models at once ("Fable"). The set is read
# against what is absent as well as what is present, so an entry is a deliberate
# abstention and not a list of words the check has not seen.
DISPLAY_NAME_EXEMPTIONS = {
    # "Grok 4.7 (Xhigh)" - a reasoning effort, and the only Grok row.
    "grok-4-7",
    # "Space Bunny" - the platform's own name; Space Bunny 2 is the premium SKU.
    "space-bunny",
    # "Claude Opus/Sonnet/Fable 5.x (Adaptive Reasoning, Max Effort, ...)" -
    # "Max Effort" is a reasoning effort and "Adaptive Reasoning" a mode.
    "claude-opus-5-5", "claude-sonnet-5-5", "claude-fable-5-1",
    # "Fable" is a brand across two numbered models; the landscape also carries
    # "Claude Fable 5.1". A family name alone is not a tier.
    "fable",
    # "MiniMax" is a vendor name that begins with "mini".
    "minimax-m3", "minimax",
}

# Subjects a provenance may name instead of a slug: the payload a score was read
# out of. `leaderboard:aa-models-on-2026-10-06` says "the figure came out of the
# archived leaderboard page", and `provenance-in-log` can corroborate that
# because the fetch log records the page. A slug cannot be corroborated that way,
# because the log records retrievals and not what a reader found inside them.
#
# The list is a closed set on purpose. A subject that is not here and is not the
# row's own slug is treated as another SKU's score, which is the defect this
# check exists for.
PAYLOAD_SUBJECTS = {
    # tools/parse-aa-models.py parses sources/aa-models.html.
    "aa-models",
    # tools/parse-aa-scores.py parses sources/aa-leaderboard-models.html.
    "aa-leaderboard-models",
}

# The kinds a provenance may put in front of its subject. `scored:` says the
# subject carries a figure and `leaderboard:` says what was read, so the two
# compose as `scored:leaderboard:<page>-on-YYYY-MM-DD`. Only the outer kind is
# optional, and `unscored:` is handled where it appears because it asserts no
# reading at all.
PROVENANCE_KINDS = {
    "scored",
    "leaderboard",
}


def check_unscored_model(pass_dir: Path) -> None:
    """A capability score must come from a leaderboard row or be marked absent.

    `model-slug-joins` only asks whether a slug is in the landscape. It cannot
    see a row that joined cleanly to a *different* SKU: the plan sells "Muse Spark
    1.3 Contributor", the landscape carries "Muse Spark 1.3", and the base model's
    48.09 was carried across to the Contributor SKU. That Contributor tier has no
    Intelligence Index at all, and it is the lane that reaches 11,029M tokens, so
    the inherited score is what made an unverified SKU look like the pass's
    answer.

    The first version tested slug *presence*, which is why it passed on that
    defect: `muse-spark-1-3` is in the landscape, so the check returned clean. A
    second version compared SKU tier words and went inert in the other direction:
    add the tier slug to the landscape and the row asserts a score the leaderboard
    does not publish, yet the check stayed silent, because the defect had moved
    from a missing tier to a present one.

    So the question is no longer "are these the same row" but **"does the board
    publish a score for this exact SKU, and is it the score the row asserts?"** The
    plan row's `aa_score_provenance` names what was read; the landscape's
    `intelligenceIndex` is what the board holds for that SKU. A provenance naming
    a SKU the landscape scores is not a defect - that is a verified score. A
    provenance naming a SKU the landscape carries with no score is a defect,
    whatever the tier words say. And a provenance naming a reading the fetch log
    does not record is `provenance-in-log`'s business.

    The authority is `data/aa-lookup.csv` where it exists, not the landscape.
    That file records what the leaderboard returned for each slug, including the
    slugs it does not carry, so it can tell "the board has no row for this tier"
    from "this derived file has no row for this tier". A landscape file can be
    edited to carry a score for a tier that does not exist on the board, and a
    check that reads only the landscape then agrees with the edit - which is how
    this check went inert the second time. Where the lookup records the slug as
    absent, a score on the plan row is borrowed no matter what the landscape
    says. Where no lookup exists for the slug, the landscape is the only evidence
    available and this check uses it.
    """
    data = pass_dir / "data"
    models = data / "models-database.csv"
    plans = data / "plan-economics.csv"
    if not models.is_file() or not plans.is_file():
        return
    mheader, mrows = read_rows(models)
    pheader, prows = read_rows(plans)
    if "slug" not in mheader or "model_slug" not in pheader:
        return
    mi = mheader.index("slug")
    name_i = mheader.index("name") if "name" in mheader else None
    score_i = mheader.index("intelligenceIndex") if "intelligenceIndex" in mheader else None

    # slug -> (present_on_board, intelligence_index) as the board actually
    # returned it. A later observation supersedes an earlier absence, so a `yes`
    # anywhere in the file wins over a `no`.
    lookup: dict[str, tuple[bool, float | None]] = {}
    lookup_path = data / "aa-lookup.csv"
    if lookup_path.is_file():
        lheader, lrows = read_rows(lookup_path)
        if "sought_slug" in lheader:
            ls = lheader.index("sought_slug")
            lp = lheader.index("present_on_board") if "present_on_board" in lheader else None
            li = lheader.index("intelligence_index") if "intelligence_index" in lheader else None
            for row in data_rows(lrows):
                if len(row) <= ls:
                    continue
                slug = row[ls].strip()
                present = (lp is not None and len(row) > lp
                           and row[lp].strip().lower() == "yes")
                score = _num(row[li]) if li is not None and len(row) > li else None
                if slug in lookup and lookup[slug][0] and not present:
                    continue
                lookup[slug] = (present, score)

    pi = pheader.index("model_slug")
    prov_i = pheader.index("aa_score_provenance") if "aa_score_provenance" in pheader else None
    model_i = pheader.index("model") if "model" in pheader else None
    plan_scores = [
        i for i, name in enumerate(pheader)
        if name.strip().lower() in ("intelligence_index", "aa_intelligence_index",
                                    "aa_score", "quality_index")
    ]
    if prov_i is None and not plan_scores:
        return
    if score_i is None and prov_i is None:
        return

    # slug -> (identity tokens of the landscape row, the score it carries)
    landscape: dict[str, tuple[tuple[str, ...], float | None]] = {}
    for r in data_rows(mrows):
        if len(r) <= mi:
            continue
        slug = r[mi].strip()
        if not slug:
            continue
        display = r[name_i] if name_i is not None and len(r) > name_i else slug
        board_score = _num(r[score_i]) if score_i is not None and len(r) > score_i else None
        landscape[slug] = (tuple(_normalise_identity(display).split()), board_score)

    for offset, row in enumerate(data_rows(prows), start=1):
        if len(row) <= pi or len(row) != len(pheader):
            continue
        slug = row[pi].strip()
        if not slug or slug == "UNKNOWN":
            continue
        prov = row[prov_i].strip().lower() if prov_i is not None and len(row) > prov_i else ""
        if prov.startswith("unscored:"):
            continue
        published = [
            row[c].strip() for c in plan_scores
            if row[c].strip() and row[c].strip().upper() != "UNKNOWN"
        ]
        asserts_score = bool(published) or bool(prov)

        if slug not in landscape:
            # Not on the board at all. Only an unscored marker saves it, and a
            # provenance asserting a reading has to be corroborated by the log.
            if published:
                failures.append(
                    f"[unscored-model] {rel(plans)} data row {offset} publishes "
                    f"{published[0]} for model_slug {slug!r}, which has no row in "
                    f"data/models-database.csv. Either the score belongs to a "
                    f"different SKU, or aa_score_provenance must read "
                    f"'unscored:<reason>'."
                )
            continue

        board_tokens, board_score = landscape[slug]

        # The lookup outranks the landscape where they disagree. `aa-lookup.csv`
        # is what the board returned; `models-database.csv` is derived from it and
        # can carry a score the board does not publish.
        if slug in lookup and not lookup[slug][0] and board_score is not None:
            failures.append(
                f"[unscored-model] {rel(plans)} data row {offset} asserts "
                f"aa_score_provenance {prov!r} for model_slug {slug!r}, and "
                f"data/models-database.csv carries that slug at "
                f"{board_score:g}. But data/aa-lookup.csv records "
                f"present_on_board=no for {slug!r}: the leaderboard has no row for "
                f"this SKU. A score on a derived file the board does not publish is "
                f"a borrowed score whatever file it sits in. Write "
                f"'unscored:<reason>'."
            )
            continue

        if prov.startswith("leaderboard:"):
            # `leaderboard:<subject>-on-YYYY-MM-DD`, optionally behind a `scored:`
            # kind. The date and the kind are stripped; what is left names what
            # was read.
            #
            # A subject is one of three things, and conflating them is how this
            # check went inert the first time:
            #
            # * this row's own slug - a per-model leaderboard page was read;
            # * the name of the payload it was read out of - `aa-models` is the
            #   archived leaderboard page, and naming it says which bytes carry
            #   the figure. This is the form that survives `provenance-in-log`,
            #   because the fetch log can vouch for a page and not for a slug;
            # * some other slug - a different SKU's score, which is the defect.
            #
            # So the page form is checked by asking the landscape whether *this*
            # row's SKU carries a score, not by comparing the subject to the
            # slug. That is the question the finding in FIX-LIST-2 §1 named:
            # slug presence is not the test, the board's own score for the exact
            # SKU is.
            claimed = re.sub(r"-on-\d{4}-\d{2}-\d{2}$", "",
                             prov.split(":", 1)[1].strip())
            claimed = re.sub(r"-ii-[\d.]+$", "", claimed)
            if claimed == slug:
                if board_score is not None:
                    continue
                failures.append(
                    f"[unscored-model] {rel(plans)} data row {offset} asserts a "
                    f"leaderboard score for model_slug {slug!r}, but "
                    f"data/models-database.csv carries that slug with no "
                    f"intelligenceIndex. The board publishes no score for this "
                    f"SKU, so any figure on this row is borrowed. Write "
                    f"'unscored:<reason>'."
                )
                continue
            if claimed in PAYLOAD_SUBJECTS:
                if board_score is not None:
                    continue
                failures.append(
                    f"[unscored-model] {rel(plans)} data row {offset} asserts "
                    f"aa_score_provenance {prov!r} for model_slug {slug!r}, but "
                    f"data/models-database.csv carries that slug with no "
                    f"intelligenceIndex. The board publishes no score for this "
                    f"SKU, so a score read out of {claimed!r} for it is borrowed. "
                    f"Write 'unscored:<reason>'."
                )
                continue
            failures.append(
                f"[unscored-model] {rel(plans)} data row {offset} asserts "
                f"aa_score_provenance {prov!r} while model_slug is {slug!r}. A "
                f"provenance that names a different SKU is that SKU's score; name "
                f"this row's own slug, name the leaderboard page the score was "
                f"read from, or write 'unscored:<reason>'."
            )
            continue

        # No usable provenance: fall back on identity, which is what catches a row
        # whose provenance is missing altogether.
        if model_i is None:
            continue
        sold = _normalise_identity(row[model_i] if len(row) > model_i else slug)
        if sold == slug.replace("-", " "):
            continue
        if sold in DISPLAY_NAME_EXEMPTIONS or slug in DISPLAY_NAME_EXEMPTIONS:
            continue
        sold_tokens = set(sold.split())
        sold_tier = {w for w in SKU_TIER_WORDS if w in sold_tokens}
        board_tier = {w for w in SKU_TIER_WORDS if w in set(board_tokens)}
        if sold_tier and not board_tier and sold_tokens - board_tier - {"<=", "and", "or"}:
            tier = ", ".join(sorted(sold_tier))
            failures.append(
                f"[unscored-model] {rel(plans)} data row {offset} sells "
                f"{row[model_i].strip()!r} - a {tier} tier - but model_slug "
                f"{slug!r} names the untilereded base model, and this row asserts a "
                f"score for it. A tiered SKU is a different product from its base "
                f"model and does not inherit its Intelligence Index; look the tier "
                f"itself up, or write 'unscored:<reason>'."
            )


def _leaderboard_models(pass_dir: Path) -> dict[str, float] | None:
    """slug -> Intelligence Index, read out of the archived leaderboard payload.

    The payload is a React Server Component flight string with escaped quotes, so
    the scores cannot be seen by grepping the raw HTML — the bar model itself,
    `deepseek-v4-1-flash` at 39.4562, is invisible to `grep -c "39\\.4562"` on that
    file. `tools/parse-aa-models.py` is the repository's own answer to that, and it
    is imported here rather than reimplemented so the check and the parser cannot
    drift apart: the earlier rejection in this review rested on a grep that could
    not see the payload, and the correction was to ask the parser.

    Returns None when the pass archives no leaderboard payload or the parser
    cannot load, in which case there is nothing to check the lookup against.
    """
    for name in ("aa-leaderboard-models.html", "aa-models.html"):
        page = pass_dir / "sources" / name
        if not page.is_file():
            continue
        spec = importlib.util.spec_from_file_location(
            "repo_parse_aa_models", Path(__file__).resolve().parent / "parse-aa-models.py"
        )
        if spec is None or spec.loader is None:
            return None
        module = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(module)
        except Exception:
            return None
        raw = page.read_text(encoding="utf-8", errors="replace")
        try:
            blob = module.flight_blob(raw)
        except Exception:
            return None
        board: dict[str, float] = {}
        for obj in module.model_objects(blob):
            slug = obj.get("slug")
            index = obj.get("intelligenceIndex")
            if slug and index is not None:
                board[slug] = float(index)
        if board:
            return board
    return None


def check_lookup_against_board(pass_dir: Path) -> None:
    """A lookup row must say what the archived leaderboard payload actually holds.

    `unscored-model` reads `aa-lookup.csv` as the authority on whether the board
    carries a SKU, and it never checks the lookup itself. Flipping
    `muse-spark-1-2-contributor` to `present_on_board=yes` with a score makes that
    check read a score the board does not publish as a verified one, and the gate
    exits 0: a file that is the authority for every other check is itself unchecked.

    The comparison is against the archived payload, parsed by the repository's own
    parser, on the two fields the lookup asserts: `present_on_board` and
    `intelligence_index`. A slug the payload carries but the lookup marks absent is
    a notFound the payload contradicts; a slug the lookup marks present that the
    payload does not carry is a presence it invents; and a score that disagrees with
    the payload's for the same slug is a figure no page holds.

    A row whose `read_date` predates the pass's own leaderboard fetch is exempt,
    because a lookup recorded against an earlier page was true of that page. The
    lookup already carries the `mimo-v2-6-flash` case in exactly this form.
    """
    lookup = pass_dir / "data" / "aa-lookup.csv"
    if not lookup.is_file():
        return
    board = _leaderboard_models(pass_dir)
    if board is None:
        return
    header, rows = read_rows(lookup)
    if "sought_slug" not in header or "present_on_board" not in header:
        return
    ls = header.index("sought_slug")
    lp = header.index("present_on_board")
    li = header.index("intelligence_index") if "intelligence_index" in header else None
    for offset, row in enumerate(data_rows(rows), start=1):
        if len(row) <= max(ls, lp):
            continue
        slug = row[ls].strip()
        present = row[lp].strip().lower() == "yes"
        score = _num(row[li]) if li is not None and len(row) > li else None
        on_board = slug in board
        if present and not on_board:
            failures.append(
                f"[lookup-against-board] {rel(lookup)} data row {offset} records "
                f"present_on_board=yes for {slug!r}, but the archived leaderboard "
                f"payload does not carry that slug. tools/parse-aa-models.py "
                f"recovers it from neither payload this pass archives."
            )
            continue
        if present and score is not None and abs(board[slug] - score) > 0.001:
            failures.append(
                f"[lookup-against-board] {rel(lookup)} data row {offset} records "
                f"{slug!r} at {score:g}, but the archived leaderboard payload "
                f"carries it at {board[slug]:g}. A score that disagrees with the "
                f"page it is attributed to is a figure no page holds."
            )


def check_shared_cap(pass_dir: Path) -> None:
    """A per-model dollar ceiling must say whether it is independent or pooled.

    OpenCode Go publishes a $60 monthly limit per model and says "Each model's
    monthly limit below determines how its usage counts toward those allowances",
    which reads as independent budgets. Several open issues report the opposite:
    models blocked at $0 recorded spend, one at $4.38 total account spend against
    a $60 pool. An independent-per-model table and a shared-pool table produce the
    same headline number for a single model and differ by the number of models a
    buyer uses, so a row publishing the ceiling without recording which it is
    cannot be planned against.

    The pool model may be declared in either `cap_model` (the 2026-10-06 column)
    or `meter_basis` (the 2026-10-02 column), and a ceiling may be published in
    `monthly_ceiling_usd`, `per_model_cap_usd` or `monthly_pool_usd`. A file that
    carries none of them has nothing to check and is skipped rather than guessed
    at.

    `cap_model` / `meter_basis` is **authoritative**. The first version also
    accepted the bare token "pool" appearing anywhere in the free-text notes,
    which lets a row whose `cap_model` literally reads `PER-MODEL` pass as long as
    some sentence in its notes happens to mention a pool. The notes are where the
    reading is argued; the column is where it is declared, and a check that reads
    the argument instead of the declaration is checking prose.
    """
    plans = pass_dir / "data" / "plan-economics.csv"
    if not plans.is_file():
        return
    header, rows = read_rows(plans)
    if not header:
        return
    cap_cols = [c for c in ("monthly_ceiling_usd", "per_model_cap_usd", "monthly_pool_usd")
                if c in header]
    model_cols = [c for c in ("cap_model", "meter_basis") if c in header]
    if not cap_cols or not model_cols:
        return
    cap_idx = [header.index(c) for c in cap_cols]
    model_idx = [header.index(c) for c in model_cols]
    for offset, row in enumerate(data_rows(rows), start=1):
        if len(row) != len(header):
            continue
        ceilings = [(row[i] or "").strip() for i in cap_idx]
        if not any(c and _num(c) is not None for c in ceilings):
            continue
        declared = " ".join((row[i] or "") for i in model_idx).lower()
        if not declared.strip():
            failures.append(
                f"[shared-cap] {rel(plans)} data row {offset} publishes a dollar "
                f"ceiling but its {'/'.join(model_cols)} cell is empty. A per-model "
                f"ceiling means nothing without saying whether it is independent or "
                f"drawn against a shared monthly pool, because the two differ by the "
                f"number of models a buyer uses in the month."
            )
            continue
        if any(token in declared for token in ("pool", "shared", "additive")):
            continue
        shown = next(c for c in ceilings if c and _num(c) is not None)
        failures.append(
            f"[shared-cap] {rel(plans)} data row {offset}: ceiling ${shown} is "
            f"published with {'/'.join(model_cols)}={row[model_idx[0]].strip()!r} and "
            f"nothing recording whether it is independent or drawn against a shared "
            f"monthly pool. State it in the cap_model column, not in the notes: a "
            f"pooled cap changes the plan's yield by the number of models a buyer "
            f"uses in the month, and that column is what a reader reads."
        )


def check_mix_declared(pass_dir: Path) -> None:
    """A derived $/M or tokens/month row must state the traffic mix behind it.

    A $/M figure is a division and its divisor is a traffic mix. The same plan on
    the same page yields figures 5.3x to 29.0x apart depending on the mix, and
    the 2026-10-02 pass exists because a $/M was published without one and a
    second was published to contradict it. A row carrying a derived price or a
    derived monthly token count without recording the mix it was computed under has
    published an assumption as a result.

    Two changes. The mix must be in a **column**, and that column must be
    non-empty: the first version accepted the substring "cache", "mix" or "%"
    anywhere in the notes, which satisfies a row whose notes read "Vendor caches
    nothing beyond the discounted tier" - a sentence that says nothing about the
    mix the row's $/M was computed under. And a file with no mix column at all has
    declared no mix anywhere, so the check now says so rather than skipping it,
    which is what left the newest pass unchecked: it published twenty derived $/M
    figures and the check demanded nothing of them.
    """
    data = pass_dir / "data"
    if not data.is_dir():
        return
    for path in sorted(data.glob("*.csv")):
        header, rows = read_rows(path)
        if not header:
            continue
        index = {name.strip().lower(): i for i, name in enumerate(header)}
        derived = [c for c in ("usd_per_mtok", "monthly_tokens_m", "tokens_m",
                               "tokens_m_at_ceiling", "blended_usd_per_mtok")
                   if c in index]
        if not derived:
            continue
        # A dedicated mix column, if the file has one. `cache` alone is not a mix
        # column: `cached_read_per_m` is a price, and a file whose only
        # "cache"-ish column is a price has declared no mix.
        mix_cols = [
            c for c in index
            if c in ("traffic_mix", "mix", "traffic_mix_used", "mix_used",
                     "assumed_mix")
        ]
        for offset, row in enumerate(data_rows(rows), start=1):
            if len(row) != len(header):
                continue
            values = [row[index[c]] for c in derived
                      if _num(row[index[c]]) is not None and _num(row[index[c]]) > 0]
            if not values:
                continue
            if not mix_cols:
                failures.append(
                    f"[mix-declared] {rel(path)} data row {offset} carries a derived "
                    f"$/M or tokens/month figure ({'/'.join(derived)}) and this file has "
                    f"no traffic-mix column. A $/M is a division and the mix is its "
                    f"divisor; add a traffic_mix column and state it per row, or mark "
                    f"the figure UNKNOWN."
                )
                continue
            if any(row[index[c]].strip() for c in mix_cols):
                continue
            failures.append(
                f"[mix-declared] {rel(path)} data row {offset} carries a "
                f"derived $/M or tokens/month figure but its "
                f"{'/'.join(sorted(mix_cols))} cell is empty. The mix is the "
                f"divisor of every figure in this row; state it there."
            )


